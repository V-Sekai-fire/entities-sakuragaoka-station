import { pathToFileURL, fileURLToPath } from 'node:url';
import path from 'node:path';
await import('./dom-stubs.mjs');
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const THREE = await import('three');
const L = await import(pathToFileURL(path.join(root, 'src/world/layout.js')).href);
const { createContext } = await import(pathToFileURL(path.join(root, 'src/core/ctx.js')).href);
const scene = new THREE.Scene(); const camera = new THREE.PerspectiveCamera();
const ctx = createContext({ scene, camera, renderer: null, audio: null, quality: { name: 'high', pixelRatio: 1, msaa: 4, shadowMap: 4096, shadowSize: 75, petals: 1 }, sunDir: new THREE.Vector3(...L.SUN_DIR).normalize() });
ctx.sky = { sun: new THREE.DirectionalLight(), hemi: new THREE.HemisphereLight(), uniforms: {} };
const mod = await import(pathToFileURL(path.join(root, 'src/world/shopsA.js')).href);
await mod.build(ctx);
scene.updateMatrixWorld(true);
let tris = 0, meshes = 0; const inst = {}; const box = new THREE.Box3(), tb = new THREE.Box3();
const groups = {};
scene.traverse(o => { if (!o.isMesh) return; meshes++; const g = o.geometry; const t = g.index ? g.index.count / 3 : g.attributes.position.count / 3;
  if (o.isInstancedMesh) { inst[o.name] = [o.count, t]; } else { tris += t; if (!g.boundingBox) g.computeBoundingBox(); tb.copy(g.boundingBox).applyMatrix4(o.matrixWorld); box.union(tb);
    let p = o; while (p.parent && !(p.parent.name||'').startsWith('shopsA:') && p.parent.parent) p = p.parent; const gn = (p.parent && p.parent.name) || 'root'; groups[gn] = (groups[gn]||0) + t; } });
console.log('plain tris', tris, 'meshes', meshes, 'box', JSON.stringify(box.min.toArray().map(v=>+v.toFixed(4))), JSON.stringify(box.max.toArray().map(v=>+v.toFixed(4))));
console.log('groups', JSON.stringify(groups));
for (const [k, v] of Object.entries(inst).sort()) console.log('inst', k, v[0], v[1]);
console.log('colliders', ctx.physics.items.length, 'wires', ctx.wires && ctx.wires.count ? ctx.wires.count() : '');
let itot=0; for (const v of Object.values(inst)) itot += v[0]*v[1]; console.log('total tris', tris+itot);
